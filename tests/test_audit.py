"""Fast tests require no database server. PostgreSQL tests are opt-in elsewhere."""

import asyncio
import io

import pytest
from alembic import command
from alembic.config import Config

from gateway.audit import AuditLog, open_audit
from gateway.database import database_url


async def test_sqlite_events_survive_reopening(tmp_path):
    path = tmp_path / "audit.sqlite3"
    first = AuditLog(path)
    await first.write("request", "stable-request", "demo", status="success")
    await first.close()
    second = AuditLog(path)
    assert await second.health()
    assert (await second.recent())[0]["payload"] == {"status": "success"}
    assert (await second.recent())[0]["request_id"] == "stable-request"
    await second.close()


async def test_sqlite_concurrent_writes_and_bounded_recent(tmp_path):
    audit = AuditLog(tmp_path / "audit.sqlite3")
    await asyncio.gather(*(audit.write("request", f"id-{i}") for i in range(16)))
    assert len(await audit.recent()) == 16
    assert len(await audit.recent(3)) == 3
    for invalid in (0, -1, 1001, True, "10"):
        with pytest.raises(ValueError):
            await audit.recent(invalid)


def test_database_url_normalizes_driver_and_preserves_escaped_password():
    url = database_url("postgresql://gateway:p%40ss%25word@localhost:55432/llm_gateway")
    assert url.drivername == "postgresql+psycopg"
    assert url.password == "p@ss%word"


@pytest.mark.parametrize("value", ["not-a-url", "sqlite:///local.db", "postgresql://localhost"])
def test_invalid_database_urls_have_safe_errors(value):
    with pytest.raises(ValueError) as error:
        database_url(value)
    assert value not in str(error.value)


async def test_audit_selection_never_silently_falls_back(monkeypatch, tmp_path):
    monkeypatch.setenv("GATEWAY_AUDIT_BACKEND", "postgres")
    monkeypatch.delenv("DATABASE_URL", raising=False)
    with pytest.raises(ValueError, match="DATABASE_URL is required"):
        await open_audit()
    # An explicit test path intentionally selects the isolated SQLite implementation.
    audit = await open_audit(tmp_path / "isolated.sqlite3")
    assert isinstance(audit, AuditLog)
    await audit.close()
    monkeypatch.setenv("GATEWAY_AUDIT_BACKEND", "unknown")
    with pytest.raises(ValueError, match="sqlite or postgres"):
        await open_audit()


def test_migration_can_render_offline_without_database_access(monkeypatch):
    monkeypatch.setenv("DATABASE_URL", "postgresql+psycopg://gateway:test@127.0.0.1/llm_gateway")
    output = io.StringIO()
    config = Config("alembic.ini", output_buffer=output)
    command.upgrade(config, "head", sql=True)
    sql = output.getvalue()
    assert "CREATE TABLE audit_events" in sql
    assert "JSONB" in sql and "GENERATED BY DEFAULT AS IDENTITY" in sql


async def test_readiness_checks_audit_storage(harness):
    async def unavailable():
        return False

    harness.app.state.audit.health = unavailable
    assert (await harness.client.get("/health/live")).status_code == 200
    response = await harness.client.get("/health/ready")
    assert response.status_code == 503 and response.json()["error"]["code"] == "not_ready"
